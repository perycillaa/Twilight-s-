/** Tentukan rarity default yang seimbang untuk kartu lama (#01–#64) bila belum memiliki properti rarity */
export function resolveCardRarity(card: { number: number; rarity?: SecretCardRarityId }): SecretCardRarityId {
  if (card.rarity) return card.rarity
  if (card.number % 9 === 0 || card.number === 1 || card.number === 36 || card.number === 64) {
    return 'cozy-special'
  }
  if (card.number % 3 === 0) return 'rare'
  return 'common'
}
